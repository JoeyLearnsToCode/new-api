type Adaptor struct {
}

func (a *Adaptor) Init(info *relaycommon.RelayInfo) {
}

func (a *Adaptor) GetRequestURL(info *relaycommon.RelayInfo) (string, error) {
	if info.RelayMode == constant.RelayModeSystemOne {
		return fmt.Sprintf("%s/v1/systemone", info.ChannelBaseUrl), nil
	}
	return "", errors.New("invalid relay mode")
}

func (a *Adaptor) SetupRequestHeader(c *gin.Context, req *http.Header, info *relaycommon.RelayInfo) error {
	channel.SetupApiRequestHeader(info, c, req)
	req.Set("Authorization", fmt.Sprintf("Bearer %s", info.ApiKey))
	// System One 用这两个开关头声明本次请求用了图片或长上下文，按客户端原样透传
	for _, header := range []string{HeaderDangerZoneImages, HeaderDangerZoneLongContext} {
		if value := c.Request.Header.Get(header); value != "" {
			req.Set(header, value)
		}
	}
	// 客户端没显式声明但请求里带了 assets 时自动开启图片开关，否则上游会直接拒绝
	if req.Get(HeaderDangerZoneImages) == "" {
		if request, ok := info.Request.(*dto.SystemOneRequest); ok && request.HasAssets() {
			req.Set(HeaderDangerZoneImages, "true")
		}
	}
	return nil
}

